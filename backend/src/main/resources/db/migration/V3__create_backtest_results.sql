CREATE TABLE backtest_results (
    id BIGINT NOT NULL AUTO_INCREMENT,
    ticker VARCHAR(32) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    theta DOUBLE NOT NULL,
    data_start DATE NOT NULL,
    data_end DATE NOT NULL,
    observations INT NOT NULL,
    min_train INT NOT NULL,
    steps INT NOT NULL,
    markov_accuracy DOUBLE NULL,
    markov_brier_score DOUBLE NULL,
    markov_log_loss DOUBLE NULL,
    markov_predictions INT NOT NULL,
    markov_skipped INT NOT NULL,
    markov_precision_macro DOUBLE NULL,
    markov_recall_macro DOUBLE NULL,
    markov_precision_by_state VARCHAR(256) NULL,
    markov_recall_by_state VARCHAR(256) NULL,
    markov_confusion_matrix VARCHAR(128) NOT NULL,
    majority_accuracy DOUBLE NULL,
    majority_brier_score DOUBLE NULL,
    majority_log_loss DOUBLE NULL,
    majority_predictions INT NOT NULL,
    majority_skipped INT NOT NULL,
    majority_precision_macro DOUBLE NULL,
    majority_recall_macro DOUBLE NULL,
    majority_precision_by_state VARCHAR(256) NULL,
    majority_recall_by_state VARCHAR(256) NULL,
    majority_confusion_matrix VARCHAR(128) NOT NULL,
    persistence_accuracy DOUBLE NULL,
    persistence_brier_score DOUBLE NULL,
    persistence_log_loss DOUBLE NULL,
    persistence_predictions INT NOT NULL,
    persistence_skipped INT NOT NULL,
    persistence_precision_macro DOUBLE NULL,
    persistence_recall_macro DOUBLE NULL,
    persistence_precision_by_state VARCHAR(256) NULL,
    persistence_recall_by_state VARCHAR(256) NULL,
    persistence_confusion_matrix VARCHAR(128) NOT NULL,
    created_at DATETIME NOT NULL,
    PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
